//! TypeScript bindings for the React UI, generated with ts-rs.
//!
//! * Regenerate: `npm run bindings` (or `openreader-backend --export-bindings <dir>`).
//! * Drift check: `cargo test` fails in `bindings_are_up_to_date` when
//!   `src/lib/generated/` no longer matches the Rust types.

use std::path::{Path, PathBuf};

use ts_rs::TS;

use crate::events::ReaderEvent;
use crate::models::*;

/// Repository directory that holds the committed bindings.
pub fn default_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/lib/generated")
}

/// Export every API type (and its dependencies) into `dir`.
pub fn export_all(dir: &Path) -> Result<(), ts_rs::ExportError> {
    std::fs::create_dir_all(dir)?;
    ReaderSettings::export_all_to(dir)?;
    VoiceProfile::export_all_to(dir)?;
    TtsEngine::export_all_to(dir)?;
    SelectionSource::export_all_to(dir)?;
    SpeakRequest::export_all_to(dir)?;
    SpeakResponse::export_all_to(dir)?;
    PlaybackState::export_all_to(dir)?;
    PlaybackSnapshot::export_all_to(dir)?;
    PlaybackEvent::export_all_to(dir)?;
    FallbackEvent::export_all_to(dir)?;
    SelectionEvent::export_all_to(dir)?;
    ReaderEvent::export_all_to(dir)?;
    HealthResponse::export_all_to(dir)?;
    TtsEngineStatus::export_all_to(dir)?;
    TtsStatusResponse::export_all_to(dir)?;
    DesktopContextSnapshot::export_all_to(dir)?;
    DocumentExtractResponse::export_all_to(dir)?;
    ExportResponse::export_all_to(dir)?;
    ApiError::export_all_to(dir)?;
    write_index(dir)?;
    Ok(())
}

/// `index.ts` re-exporting every generated file, sorted for stable output.
fn write_index(dir: &Path) -> std::io::Result<()> {
    let mut names: Vec<String> = std::fs::read_dir(dir)?
        .flatten()
        .filter_map(|entry| {
            let name = entry.file_name().to_string_lossy().into_owned();
            let stem = name.strip_suffix(".ts")?.to_string();
            (stem != "index").then_some(stem)
        })
        .collect();
    names.sort();
    let mut index = String::from("// This file was generated by `npm run bindings`. Do not edit this file manually.\n\n");
    for name in names {
        index.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
    }
    std::fs::write(dir.join("index.ts"), index)
}

fn read_dir_files(dir: &Path) -> std::collections::BTreeMap<String, String> {
    std::fs::read_dir(dir)
        .map(|entries| {
            entries
                .flatten()
                .map(|entry| {
                    (
                        entry.file_name().to_string_lossy().into_owned(),
                        std::fs::read_to_string(entry.path()).unwrap_or_default(),
                    )
                })
                .collect()
        })
        .unwrap_or_default()
}

/// Names of generated files that differ from (or are missing in) `committed`.
pub fn stale_files(committed: &Path) -> Result<Vec<String>, ts_rs::ExportError> {
    let fresh = tempfile::tempdir()?;
    export_all(fresh.path())?;
    let expected = read_dir_files(fresh.path());
    let actual = read_dir_files(committed);
    let mut stale: Vec<String> = expected
        .iter()
        .filter(|(name, content)| actual.get(*name) != Some(content))
        .map(|(name, _)| name.clone())
        .collect();
    stale.extend(actual.keys().filter(|name| !expected.contains_key(*name)).cloned());
    Ok(stale)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `npm run bindings` runs this ignored test to rewrite `src/lib/generated/`.
    #[test]
    #[ignore]
    fn export_bindings() {
        let dir = default_dir();
        if dir.exists() {
            std::fs::remove_dir_all(&dir).unwrap();
        }
        export_all(&dir).unwrap();
    }

    #[test]
    fn bindings_are_up_to_date() {
        let stale = stale_files(&default_dir()).unwrap();
        assert!(
            stale.is_empty(),
            "TypeScript bindings in src/lib/generated are stale: {stale:?}. Run `npm run bindings`."
        );
    }

    #[test]
    fn bindings_use_snake_case_json_names_and_numbers() {
        let decl = PlaybackState::decl();
        assert!(decl.contains("word_start: number | null"), "{decl}");
        assert!(decl.contains("revision: number"), "{decl}");
        let settings = ReaderSettings::decl();
        assert!(settings.contains("min_selection_chars: number"), "{settings}");
        assert!(TtsEngine::decl().contains("\"edge\" | \"piper\""));
    }
}
